//! **라이브 API를 치지 않는다.** 전부 기록된 fixture JSON에 대해 돈다.
//! 이유는 두 가지다: CI에 자격증명이 없고, 라이브 테스트는 Jira 데이터가 바뀌면
//! 우리 코드가 멀쩡한데도 빨개진다.
